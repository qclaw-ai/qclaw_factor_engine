# 进程池 worker 侧共享行情面板，避免每个任务重复传输同一份 price_df。
_WORKER_PRICE_DF: Optional[pd.DataFrame] = None


def _init_factor_compute_worker(price_df: pd.DataFrame) -> None:
    """初始化进程池 worker 的只读行情面板。"""
    global _WORKER_PRICE_DF
    _WORKER_PRICE_DF = price_df


def _compute_factor_processed_series_worker(task: Tuple[str, str, str]) -> Tuple[str, str, Optional[pd.Series], Optional[str], float]:
    """
    进程池 worker：执行单因子计算 + 标准化。

    返回：
    - factor_id / factor_name
    - processed_series（成功时）
    - error_message（失败时）
    - elapsed_seconds
    """
    factor_id, factor_name, formula = task

    if _WORKER_PRICE_DF is None:
        return factor_id, factor_name, None, "worker 未初始化行情面板", 0.0

    started = time.time()

    try:
        raw_series = compute_factor_values(formula, _WORKER_PRICE_DF)
        processed_series = winsorize_and_standardize(raw_series)
    except Exception as e:
        return factor_id, factor_name, None, str(e), time.time() - started

    return factor_id, factor_name, processed_series, None, time.time() - started


def _auth_jq_if_configured(cfg: Config, config_file: str) -> None:
    """
    尝试登录聚宽（仅在需要解析非 ALL/CUSTOM 域时会调用）。

    统一配置约定：
    - 仅读取当前 config_file（根配置）内的 [jq]
    """
    jq_user = ""
    jq_password = ""
    try:
        jq_user = (cfg.get("jq", "user", fallback="") or "").strip()
        jq_password = (cfg.get("jq", "password", fallback="") or "").strip()
    except Exception:
        jq_user = ""
        jq_password = ""

    if not jq_user or not jq_password:
        raise RuntimeError(
            f"未找到聚宽账号配置，无法解析分域股票池（config_file={config_file}）。"
        )

    jqdatasdk.auth(jq_user, jq_password)


def _filter_price_df_by_universe(
    cfg: Config,
    config_file: str,
    price_df: pd.DataFrame,
    universe: str,
    end_date: str,
) -> pd.DataFrame:
    """
    按领域筛选行情面板（MultiIndex: trade_date, stock_code）。

    约定：
    - ALL：不筛选（保持现有全市场口径）
    - STOCK：仅保留 A 股代码后缀 .SH/.SZ
    - CUSTOM/HS300/ZZ500/INDEX/CSI/ETF/LOF/FUTURES：通过 common.universe_service 解析

    说明：factor_engine 主入口已改为在 _load_stock_daily 的 SQL 侧按域过滤；本函数保留供测试或
    与内存筛选口径对照，避免与 _load_stock_daily 分支逻辑漂移。
    """
    u = normalize_universe_code(universe)

    if u == "ALL":
        return price_df

    if u == "STOCK":
        stock_codes = price_df.index.get_level_values("stock_code")
        mask = stock_codes.str.endswith(".SH") | stock_codes.str.endswith(".SZ")
        return price_df[mask]

    if u in ("CUSTOM", "HS300", "ZZ500", "INDEX", "CSI", "ETF", "LOF", "FUTURES"):
        _auth_jq_if_configured(cfg, config_file=config_file)
        internal_codes, _, _, _ = resolve_universe_for_jq(
            cfg=cfg,
            end_date=end_date,
            section="factor_engine",
            universe_hint=u,
        )
        code_set = set(internal_codes)
        if not code_set:
            return price_df.iloc[0:0]

        mask = price_df.index.get_level_values("stock_code").isin(code_set)
        return price_df[mask]

    raise ValueError(f"不支持的 factor_engine.universe={u}")


def _upsert_factor_value_file(
    session,
    *,
    factor_id: str,
    factor_name: str,
    universe: str,
    rel_path: str,
    date_start: str,
    date_end: str,
    batch_id: str,
    stage: str,
    is_rebase: bool,
) -> None:
    """
    写入/更新 factor_value_files（artifact_type=batch_csv）。

    说明：
    - 唯一键：factor_id + universe + artifact_type + date_start + date_end
    - 路径统一存相对仓库根 POSIX 路径
    """
    # 统一转 date，避免 SQL 里做类型强转导致方言差异问题。
    ds = date.fromisoformat(date_start)
    de = date.fromisoformat(date_end)

    params = {
        "factor_id": factor_id,
        "universe": universe,
        "rel_path": rel_path,
        "date_start": ds,
        "date_end": de,
        "batch_id": batch_id,
        "stage": stage,
        "is_rebase": is_rebase,
        "comment": (
            "generated by factor_engine_runner "
            f"universe={universe} batch_id={batch_id} stage={stage} is_rebase={is_rebase}"
        ),
    }

    # 先更新已存在记录。这样不依赖 ON CONFLICT 推断部分唯一索引（WHERE artifact_type='batch_csv'）。
    # 每次 upsert 用 SAVEPOINT 隔离失败，避免一个因子写库失败导致整个 session 进入 aborted。
    # 并且把 factor_basic 的最小 upsert 放在同一个 SAVEPOINT 内，确保外键检查在同一事务视图内可见。
    with session.begin_nested():
        # 先保证 factor_basic 存在，否则插 factor_value_files 会被外键拒绝并导致事务进入 aborted。
        # 这里做最小 upsert：只写必填字段 factor_id / factor_name，其余字段后续可由 pipeline 补齐。
        session.execute(
            text(
                """
                INSERT INTO factor_basic (
                    factor_id,
                    factor_name
                ) VALUES (
                    :factor_id,
                    :factor_name
                )
                ON CONFLICT (factor_id) DO NOTHING
                """
            ),
            {
                "factor_id": factor_id,
                "factor_name": factor_name,
            },
        )

        updated = session.execute(
            text(
                """
                UPDATE factor_value_files
                SET
                    rel_path = :rel_path,
                    batch_id = :batch_id,
                    stage = :stage,
                    is_rebase = :is_rebase,
                    created_at = CURRENT_TIMESTAMP,
                    comment = :comment
                WHERE factor_id = :factor_id
                  AND universe = :universe
                  AND artifact_type = 'batch_csv'
                  AND date_start = :date_start
                  AND date_end = :date_end
                """
            ),
            params,
        )
        if updated.rowcount and updated.rowcount > 0:
            return

        # 未命中更新时再插入新行。
        session.execute(
            text(
                """
                INSERT INTO factor_value_files (
                    factor_id,
                    universe,
                    artifact_type,
                    rel_path,
                    date_start,
                    date_end,
                    trade_date,
                    batch_id,
                    stage,
                    is_rebase,
                    created_at,
                    comment
                ) VALUES (
                    :factor_id,
                    :universe,
                    'batch_csv',
                    :rel_path,
                    :date_start,
                    :date_end,
                    NULL,
                    :batch_id,
                    :stage,
                    :is_rebase,
                    CURRENT_TIMESTAMP,
                    :comment
                )
                """
            ),
            params,
        )


def _factor_value_files_batch_csv_ids_for_job_key(
    session,
    *,
    factor_id: str,
    universe: str,
    date_start: date,
    date_end: date,
) -> List[int]:
    """
    按 batch_csv 写入键查询 factor_value_files 行 id。

    - 应与 _upsert_factor_value_file / 落库的 date_start、date_end 一致。
    - UNIQUE 索引下常为 0/1 行；若为多行则说明数据异常。
    """
    rows = session.execute(
        text(
            """
            SELECT id
            FROM factor_value_files
            WHERE factor_id = :factor_id
              AND universe = :universe
              AND artifact_type = 'batch_csv'
              AND date_start = :date_start
              AND date_end = :date_end
            ORDER BY id ASC
            """
        ),
        {
            "factor_id": factor_id,
            "universe": universe,
            "date_start": date_start,
            "date_end": date_end,
        },
    ).fetchall()
    return [int(r[0]) for r in rows]


