def winsorize_and_standardize(series: pd.Series) -> pd.Series:
    """按文档约定进行去极值 + 标准化

    - 去极值：按当日截面 1%–99% 分位数剪裁
    - 标准化：按当日截面 Z-score
    """
    df = series.to_frame("factor_value").copy()

    # 截面去极值
    def _winsorize(group: pd.DataFrame) -> pd.DataFrame:
        s = group["factor_value"]
        if s.isna().all():
            return group
        q01 = s.quantile(0.01)
        q99 = s.quantile(0.99)
        group["factor_value"] = s.clip(lower=q01, upper=q99)
        return group

    df = df.groupby(level="trade_date", group_keys=False).apply(_winsorize)

    # 截面标准化
    def _zscore(group: pd.DataFrame) -> pd.DataFrame:
        s = group["factor_value"]
        mean = s.mean()
        std = s.std()
        if std == 0 or pd.isna(std):
            group["factor_value"] = 0.0
        else:
            group["factor_value"] = (s - mean) / std
        return group

    df = df.groupby(level="trade_date", group_keys=False).apply(_zscore)

    return df["factor_value"]


def _dedupe_factor_id_sequence(override: Sequence[str]) -> List[str]:
    """P1 / worker：对显式 factor_id 列表去空白、去重且保序，供 factor_ids_override 使用。"""
    out: List[str] = []
    seen = set()
    for x in override:
        s = str(x).strip()
        if s and s not in seen:
            seen.add(s)
            out.append(s)
    return out


def run_factor_engine(
    config_file: str = "config.ini",
    *,
    start_date_override: Optional[str] = None,
    end_date_override: Optional[str] = None,
    publish_start_date_override: Optional[str] = None,
    batch_id_override: Optional[str] = None,
    stage_override: Optional[str] = None,
    is_rebase_override: Optional[bool] = None,
    # 与 [factor_engine] 中 factor_ids / universe 的显式覆写，避免为每条任务写临时 ini。
    # - factor_ids_override 为 None：从配置文件读取（空串表示全量 ALL，保持旧语义）。
    # - factor_ids_override 非 None：必须得到至少一个 factor_id，否则 ValueError；忽略 ini 的 factor_ids。
    # - universe_override 为 None：从配置文件读取；非 None 则经 normalize 后使用，并忽略 ini 的 universe。
    factor_ids_override: Optional[Sequence[str]] = None,
    universe_override: Optional[str] = None,
    # skip_if_batch_csv_record_exists_override：None 读 ini；True/False 显式覆盖 skip_if_batch_csv_record_exists。
    skip_if_batch_csv_record_exists_override: Optional[bool] = None,
    # daily_csv_mode：日更语义，CSV 写入 factor_values/daily/by_universe/... ，factor_value_files.artifact_type=daily_csv，
    # 与同仓库 factor_export_cos 中 daily_override_batch 对齐。要求 publish_start_date 与 end_date 同一天；
    # start_date 可更早（回看/warmup），与 incremental 单笔单日任务一致。
    daily_csv_mode: bool = False,
) -> None:
    """
    因子主计算（含行情加载、算子、落 CSV、回写 factor_value_files）。

    与 P1 / factor_pipeline_job 对接时，推荐优先传 ``factor_ids_override`` / ``universe_override``，
    与单条 job 参数对齐；其余 [factor_engine] 与 [jq] 等仍来自 ``config_file`` 根配置。

    开关 ``skip_if_batch_csv_record_exists`` 默认开启：在计算前查询 ``factor_value_files``，
    当前任务对应的 ``batch_csv`` / ``daily_csv``（daily_csv_mode 时按 trade_date）索引键，
    只要已存在任意一行则跳过该因子不落 CSV。
    配置文件或旧键设为 false（或 CLI ``--no-skip-if-batch-csv-record-exists``）可强制重算。
    （若启用且同键多条，会先 INFO 跳过并额外 WARNING。）
    """
    logger.info(
        "启动 factor_engine_runner daily_csv_mode=%s",
        bool(daily_csv_mode),
    )

    cfg = Config(config_file=config_file)

    start_date = start_date_override or cfg.get("factor_engine", "start_date", fallback="2024-01-01")
    end_date = end_date_override or cfg.get(
        "factor_engine",
        "end_date",
        fallback=datetime.now().strftime("%Y-%m-%d"),
    )
    if publish_start_date_override is not None:
        publish_start_date = publish_start_date_override
    elif daily_csv_mode:
        # 日报/单日任务：默认以区间右端点为发布日与 trade_date（左端点为加载/warmup 起点）。
        publish_start_date = end_date
    else:
        publish_start_date = start_date

    if daily_csv_mode:
        d_pub = date.fromisoformat(str(publish_start_date).strip()[:10])
        d_end = date.fromisoformat(str(end_date).strip()[:10])
        if d_pub != d_end:
            raise ValueError(
                f"daily_csv_mode 要求发布日为单日区间：publish_start_date ({d_pub}) 须等于 end_date ({d_end})"
            )

    if factor_ids_override is not None:
        factor_ids = _dedupe_factor_id_sequence(factor_ids_override)
        if not factor_ids:
            raise ValueError(
                "factor_ids_override 经去重后为空：请传至少一个 factor_id，"
                "或改为 factor_ids_override=None 以使用配置文件中的 [factor_engine].factor_ids"
            )
        logger.info("使用参数 factor_ids_override，忽略 [factor_engine].factor_ids 原文")
    else:
        factor_ids_raw = cfg.get("factor_engine", "factor_ids", fallback="").strip()
        factor_ids = [
            fid.strip()
            for fid in factor_ids_raw.split(",")
            if fid.strip()
        ]

    if universe_override is not None:
        u0 = str(universe_override).strip()
        if not u0:
            raise ValueError(
                "universe_override 只含空白不合法；请传 None 使用 [factor_engine].universe 或传有效域代码"
            )
        universe = normalize_universe_code(u0)
        logger.info("使用参数 universe_override，忽略 [factor_engine].universe 原文")
    else:
        universe = normalize_universe_code(
            cfg.get("factor_engine", "universe", fallback="ALL")
        )

    batch_id = (batch_id_override or cfg.get("factor_engine", "batch_id", fallback="")).strip()
    stage = (
        (stage_override or cfg.get("factor_engine", "stage", fallback="candidate") or "candidate")
        .strip()
        .lower()
    )
    is_rebase_cfg = bool(cfg.getboolean("factor_engine", "is_rebase", fallback=False))
    is_rebase = is_rebase_override if is_rebase_override is not None else is_rebase_cfg

    if not batch_id:
        # 默认批次号：inc_YYYYMMDD；重算模式则前缀 rebase_。
        batch_prefix = "rebase" if is_rebase else "inc"
        batch_id = f"{batch_prefix}_{end_date.replace('-', '')}"

    if stage not in ("candidate", "production", "deprecated"):
        raise ValueError(f"配置错误：factor_engine.stage 不合法（{stage}）")

    # 优先读新键 skip_if_batch_csv_record_exists；若无则兼容旧键 skip_if_batch_csv_duplicate；均无则默认「开」。
    if skip_if_batch_csv_record_exists_override is None:
        v = cfg.getboolean("factor_engine", "skip_if_batch_csv_record_exists", fallback=None)
        if v is None:
            v = cfg.getboolean("factor_engine", "skip_if_batch_csv_duplicate", fallback=None)
        if v is None:
            v = True
        skip_if_batch_csv_record_exists = bool(v)
    else:
        skip_if_batch_csv_record_exists = bool(skip_if_batch_csv_record_exists_override)

    # 黑名单：配置里可选的 skip_factor_ids，用逗号分隔
    skip_ids_raw = cfg.get("factor_engine", "skip_factor_ids", fallback="").strip()
    skip_factor_ids: List[str] = [
        fid.strip()
        for fid in skip_ids_raw.split(",")
        if fid.strip()
    ]

    logger.info(
        f"配置 - start_date={start_date}, end_date={end_date}, publish_start_date={publish_start_date}, "
        f"factor_ids={factor_ids or 'ALL'}, universe={universe}, "
        f"batch_id={batch_id}, stage={stage}, is_rebase={is_rebase}, "
        f"skip_if_batch_csv_record_exists={skip_if_batch_csv_record_exists}"
    )

    all_factors = load_all_factors()
    if not all_factors:
        logger.error("未解析到任何因子定义，退出")
        return

    # 过滤需要计算的因子
    if factor_ids:
        factors = [f for f in all_factors if f.factor_id in factor_ids]
        missing = set(factor_ids) - {f.factor_id for f in factors}
        if missing:
            logger.warning(f"以下因子ID在因子文档中未找到: {missing}")
    else:
        factors = all_factors

    if skip_factor_ids:
        before = len(factors)
        factors = [f for f in factors if f.factor_id not in skip_factor_ids]
        skipped = before - len(factors)
        if skipped:
            logger.info(
                f"根据配置 skip_factor_ids 跳过 {skipped} 个因子: {sorted(skip_factor_ids)}"
            )

    compute_workers_raw = str(
        cfg.get("factor_engine", "compute_workers", fallback="0")
    ).strip()
    try:
        compute_workers = int(compute_workers_raw) if compute_workers_raw else 0
    except ValueError:
        compute_workers = 0

    if compute_workers <= 0:
        compute_workers = min((os.cpu_count() or 1), 8)

    logger.info(
        "本次将计算 %s 个因子（仅多进程模式，compute_workers=%s）",
        len(factors),
        compute_workers,
    )

    # 拉行情：非 ALL 时在 SQL 侧按股票池过滤，避免全市场进内存（见 _load_stock_daily）
    price_df = _load_stock_daily(
        config_file=config_file,
        start_date=start_date,
        end_date=end_date,
        cfg=cfg,
        universe=universe,
    )
    if price_df.empty:
        logger.error("行情数据为空，无法计算因子")
        return

    db_manager = get_db_manager(config_file=config_file)
    session = db_manager.get_session()
    project_root = Path(__file__).resolve().parents[2]

    try:
        compute_factor_tasks: List[Tuple[str, str, str]] = []

        for factor in factors:
            logger.info(f"开始计算因子: {factor.factor_id} - {factor.factor_name}")

            # 可选：若 factor_value_files 已存在当前任务索引行，则跳过计算（便于幂等重跑）。
            if skip_if_batch_csv_record_exists:
                if daily_csv_mode:
                    td_key = date.fromisoformat(str(end_date).strip()[:10])
                    row_ids = _factor_value_files_daily_csv_ids_for_trade_date(
                        session,
                        factor_id=factor.factor_id,
                        universe=universe,
                        trade_date=td_key,
                    )
                    if len(row_ids) >= 1:
                        logger.info(
                            "跳过因子计算：factor_value_files 已存在 daily_csv 索引记录。"
                            "factor_id=%s universe=%s trade_date=%s row_count=%s ids=%s",
                            factor.factor_id,
                            universe,
                            td_key.isoformat(),
                            len(row_ids),
                            row_ids,
                        )
                        if len(row_ids) > 1:
                            logger.warning(
                                "factor_value_files 同一 daily_csv 键存在多条记录（数据异常，应唯一）：ids=%s",
                                row_ids,
                            )
                        continue
                else:
                    ds_key = date.fromisoformat(str(publish_start_date).strip()[:10])
                    de_key = date.fromisoformat(str(end_date).strip()[:10])
                    row_ids = _factor_value_files_batch_csv_ids_for_job_key(
                        session,
                        factor_id=factor.factor_id,
                        universe=universe,
                        date_start=ds_key,
                        date_end=de_key,
                    )
                    if len(row_ids) >= 1:
                        logger.info(
                            "跳过因子计算：factor_value_files 已存在 batch_csv 索引记录。"
                            "factor_id=%s universe=%s date_start=%s date_end=%s row_count=%s ids=%s",
                            factor.factor_id,
                            universe,
                            ds_key.isoformat(),
                            de_key.isoformat(),
                            len(row_ids),
                            row_ids,
                        )
                        if len(row_ids) > 1:
                            logger.warning(
                                "factor_value_files 同一 batch_csv 自然键存在多条记录（数据异常，应唯一）：ids=%s",
                                row_ids,
                            )
                        continue

            # 计算前先做公式静态校验：仅将“可翻译”的公式送入并行计算队列。
            try:
                validate_factor_dsl_formula(factor.formula)
            except Exception as e:
                logger.error(
                    "跳过因子：公式校验失败（factor_id=%s factor_name=%s err=%s）",
                    factor.factor_id,
                    factor.factor_name,
                    e,
                )
                continue

            compute_factor_tasks.append(
                (factor.factor_id, factor.factor_name, factor.formula)
            )

        # 计算阶段：固定多进程，不再降级串行。
        computed_result_map: dict = {}
        compute_order_factor_ids: List[str] = [x[0] for x in compute_factor_tasks]

        if compute_factor_tasks:
            logger.info(
                "开始多进程计算，共 %s 个任务，workers=%s",
                len(compute_factor_tasks),
                compute_workers,
            )
            try:
                with concurrent.futures.ProcessPoolExecutor(
                    max_workers=compute_workers,
                    initializer=_init_factor_compute_worker,
                    initargs=(price_df,),
                ) as executor:
                    future_map = {
                        executor.submit(_compute_factor_processed_series_worker, task): task[0]
                        for task in compute_factor_tasks
                    }

                    completed_count = 0
                    total_count = len(future_map)

                    # 终端用 tqdm 展示细粒度进度；日志文件则写里程碑进度，避免动态刷新字符污染日志。
                    progress_iter = tqdm(
                        concurrent.futures.as_completed(future_map),
                        total=total_count,
                        desc="factor compute",
                        disable=not sys.stderr.isatty(),
                    )

                    for future in progress_iter:
                        factor_id_ret, factor_name_ret, processed_series, error_message, elapsed = future.result()
                        completed_count += 1

                        if (completed_count % 20 == 0) or (completed_count == total_count):
                            logger.info(
                                "并行计算进度：%s/%s（%.1f%%）",
                                completed_count,
                                total_count,
                                (completed_count / total_count) * 100.0,
                            )

                        if error_message:
                            logger.error(
                                "计算因子失败（并行）：factor_id=%s factor_name=%s elapsed=%.3fs err=%s",
                                factor_id_ret,
                                factor_name_ret,
                                elapsed,
                                error_message,
                            )
                            continue

                        computed_result_map[factor_id_ret] = (factor_name_ret, processed_series)
                        logger.info(
                            "计算因子完成（并行）：factor_id=%s factor_name=%s elapsed=%.3fs",
                            factor_id_ret,
                            factor_name_ret,
                            elapsed,
                        )
            except Exception as e:
                logger.error(
                    "多进程计算阶段异常，本批次不再串行回退。err=%s",
                    e,
                )

        for factor_id in compute_order_factor_ids:
            if factor_id not in computed_result_map:
                continue

            factor_name, processed_series = computed_result_map[factor_id]

            # 简单输出前几行结果用于检查
            df_out = processed_series.to_frame("factor_value").reset_index()
            # 增量模式下 start_date 可能是 warmup 回看起点；发布时仅保留业务区间 publish_start_date~end_date。
            df_out["trade_date"] = pd.to_datetime(df_out["trade_date"])
            df_out = df_out[
                (df_out["trade_date"] >= pd.Timestamp(publish_start_date))
                & (df_out["trade_date"] <= pd.Timestamp(end_date))
            ].copy()
            logger.info(
                f"因子 {factor_id} 样例数据（前5行）:\n"
                f"{df_out.head().to_string(index=False)}"
            )

            # 导出 CSV：batch 沿用 by_universe 区间文件名；daily_csv_mode 与同仓库 daily_factor_values 路径一致。
            publish_iso = str(publish_start_date).strip()[:10]
            if daily_csv_mode:
                output_dir = os.path.join(
                    "factor_values",
                    "daily",
                    "by_universe",
                    universe,
                    publish_iso,
                )
                csv_name = f"{factor_id}.csv"
            else:
                output_dir = os.path.join("factor_values", "by_universe", universe)
                csv_name = (
                    f"{factor_id}_{universe}_{publish_start_date}_{end_date}.csv"
                    .replace(":", "")
                    .replace(" ", "")
                )

            os.makedirs(output_dir, exist_ok=True)
            csv_path = os.path.join(output_dir, csv_name)
            df_out.to_csv(csv_path, index=False)
            logger.info(f"因子 {factor_id} 结果已导出到 CSV: {csv_path}")

            # 回写 factor_value_files（batch_csv / daily_csv）
            try:
                rel_path = Path(csv_path).resolve().relative_to(project_root).as_posix()
            except ValueError:
                rel_path = Path(csv_path).as_posix()

            try:
                if daily_csv_mode:
                    _upsert_factor_value_files_daily_csv(
                        session,
                        factor_id=factor_id,
                        universe=universe,
                        rel_path_posix=rel_path,
                        trade_date=publish_iso,
                    )
                else:
                    _upsert_factor_value_file(
                        session,
                        factor_id=factor_id,
                        factor_name=factor_name,
                        universe=universe,
                        rel_path=rel_path,
                        date_start=publish_start_date,
                        date_end=end_date,
                        batch_id=batch_id,
                        stage=stage,
                        is_rebase=is_rebase,
                    )
                # 每个因子独立提交，提升可观测性与容错性：
                # - 中途可在 DB 看到已完成因子
                # - 单因子失败不会回滚此前成功写入
                session.commit()
            except Exception as e:
                # 不中断主计算；记录错误供后续补写。
                logger.error(
                    f"写入 factor_value_files 失败，factor_id={factor_id}, "
                    f"universe={universe}, path={rel_path}, err={e}"
                )
                # 避免 session 落入 aborted 状态影响后续因子；这里显式回滚到干净状态。
                session.rollback()
    except Exception:
        session.rollback()
        raise
    finally:
        session.close()


